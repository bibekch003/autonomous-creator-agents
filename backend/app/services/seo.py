"""SEO agent service: titles, descriptions, hashtags, captions, platform variants.

Deterministic engine by default (no keys, no cost, same output every run). The LLM
adapter is used only when configured, and the result records which one ran.
"""
from __future__ import annotations

import re

from app.ai import client as ai

STOPWORDS = set("""a an the and or but if then than that this these those i you he she it we they
is are was were be been being do does did doing have has had having of to in on for with at by from
as not no so just about into over after before your my our their his her its me us them what which
who whom when where how very really quite more most much many few some any all can could will would
should may might must shall like get got make made own same other another""".split())

PLATFORM_TONE = {
    "youtube_shorts": {"label": "YouTube Shorts", "cta": "Full breakdown on the channel."},
    "instagram_reel": {"label": "Instagram Reels", "cta": "Save this for your next edit."},
    "tiktok": {"label": "TikTok", "cta": "Part two if this helps."},
    "youtube": {"label": "YouTube", "cta": "Watch the full video on the channel."},
    "square": {"label": "LinkedIn", "cta": "Curious how others handle this."},
}


def topic_from(text: str, fallback: str) -> str:
    """Cheap keyword phrase from a transcript, or the fallback (usually the title)."""
    if not text:
        return fallback
    words = [w for w in re.findall(r"[A-Za-z][A-Za-z'\-]+", text)
             if len(w) > 3 and w.lower() not in STOPWORDS]
    if not words:
        return fallback
    freq: dict[str, int] = {}
    for w in words:
        freq[w.lower()] = freq.get(w.lower(), 0) + 1
    best = max(freq, key=lambda w: (freq[w], -words.index(next(x for x in words if x.lower() == w))))
    return best


def hashtags(topic: str, platform: str, limit: int = 6) -> list[str]:
    base = [w for w in re.split(r"[^A-Za-z0-9]+", topic.lower()) if len(w) > 2][:3]
    tags = [f"#{w}" for w in base]
    tags += ["#shorts", "#creator", "#contentcreator", "#editing", "#howto"]
    seen, out = set(), []
    for t in tags:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out[:limit]


def generate(*, topic: str, transcript: str = "", platform: str = "youtube_shorts",
             persona: str = "", clip_title: str = "") -> dict:
    """Return titles (3), description, hashtags, caption and per-platform text."""
    subject = (topic or topic_from(transcript, clip_title or "this")).strip()
    subject = subject[:80] or "this"
    tone = PLATFORM_TONE.get(platform, PLATFORM_TONE["youtube_shorts"])

    if ai.is_enabled():
        prompt = (
            "You write social copy for a solo creator. Return STRICT JSON with keys: "
            "titles (array of exactly 3 strings, each under 70 chars), description (string, "
            "2-3 sentences), hashtags (array of 5-6 strings starting with #), caption "
            "(string under 90 chars).\n"
            f"Creator persona: {persona or 'direct, friendly, no hype'}\n"
            f"Platform: {tone['label']}\nSubject: {subject}\n"
            f"Transcript excerpt: {transcript[:1200]}"
        )
        data = ai.complete_json(prompt)
        if data:
            titles = [str(t)[:120] for t in (data.get("titles") or []) if str(t).strip()][:3]
            if len(titles) == 3:
                return {
                    "titles": titles,
                    "description": str(data.get("description", ""))[:1200],
                    "hashtags": [str(h) for h in (data.get("hashtags") or [])][:8]
                                or hashtags(subject, platform),
                    "caption": str(data.get("caption", ""))[:160],
                    "platform_text": _platform_variants(subject, tone, str(data.get("caption", ""))),
                    "source": "llm",
                    "note": "Copy written by the configured LLM endpoint.",
                }

    titles = [
        f"{subject.title()} — the part nobody explains",
        f"I fixed my {subject} in one sitting. Here's the change.",
        f"Stop getting {subject} wrong (start here)",
    ]
    description = (
        f"{subject.title()} in the shortest version I can give. "
        f"I go through what actually changed and why it worked, without the theory detour. "
        f"{tone['cta']}"
    )
    caption = f"{subject.title()} — the one change that mattered."
    return {
        "titles": titles,
        "description": description,
        "hashtags": hashtags(subject, platform),
        "caption": caption,
        "platform_text": _platform_variants(subject, tone, caption),
        "source": "offline",
        "note": ("Generated by the built-in template engine. Set ACA_LLM_API_KEY to have a "
                 "model write this copy instead."),
    }


def _platform_variants(subject: str, tone: dict, caption: str) -> dict:
    return {
        "youtube_shorts": f"{caption} #shorts",
        "instagram_reel": f"{subject.title()} ✨\n{tone['cta']}",
        "tiktok": f"{subject.title()} — {tone['cta']}",
        "youtube": f"{subject.title()}: what changed and why it worked. {tone['cta']}",
        "square": f"{subject.title()}\n\nA short breakdown of the one change that mattered. "
                  f"{tone['cta']}",
    }
